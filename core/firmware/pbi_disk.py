# Assembles pbi_disk.s (the ROM of the classic machine's PBI disk) with ca65 / ld65 and writes
# pbi_disk.h: the code (the ROM up to its last used byte) and the offsets of the bytes the
# firmware writes. pbi_disk.h is kept in the repository, so the firmware builds without cc65;
# run this after changing pbi_disk.s.
import os, re, subprocess, tempfile
here = os.path.dirname(os.path.abspath(__file__))
with tempfile.TemporaryDirectory() as t:
    cfg = os.path.join(t, "p.cfg")
    open(cfg, "w").write("MEMORY { ROM: start = $D800, size = $0800, file = %O; }\n"
                         "SEGMENTS { CODE: load = ROM, type = ro; }\n")
    o, b, lbl = (os.path.join(t, n) for n in ("p.o", "p.bin", "p.lbl"))
    subprocess.run(["ca65", "-g", "-o", o, os.path.join(here, "pbi_disk.s")], check=True)
    subprocess.run(["ld65", "-C", cfg, "-o", b, "-Ln", lbl, o], check=True)
    img = open(b, "rb").read()
    sym = {m.group(2): int(m.group(1), 16) for m in re.finditer(r"al ([0-9A-F]+) \.(\w+)", open(lbl).read())}
assert len(img) == 0x800 and img[3] == 0x80 and img[0x0B] == 0x91
code = img[:sym["P_DONE"] - 0xD800].rstrip(b"\xff")
out = ["// Generated by pbi_disk.py from pbi_disk.s: do not edit.",
       "#define PBI_P_DONE   0x%03X    // the served bit (the ROM's copy of the request bit)" % (sym["P_DONE"] - 0xD800),
       "#define PBI_P_RESULT 0x%03X    // 0 not handled, 1 the bytes are in the buffer, $80+ SIO error" % (sym["P_RESULT"] - 0xD800),
       "#define PBI_P_BUF    0x%03X    // 256 bytes" % (sym["P_BUF"] - 0xD800),
       "static const unsigned char pbi_disk_img[%d] = {" % len(code)]
for i in range(0, len(code), 16):
    out.append("    " + ", ".join("0x%02X" % x for x in code[i:i + 16]) + ",")
out.append("};")
open(os.path.join(here, "pbi_disk.h"), "w").write("\n".join(out) + "\n")
print("pbi_disk.h: %d bytes of code" % len(code))
