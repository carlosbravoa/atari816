# Assembles bas_loader.s (the boot program of "Run in Atari") with ca65 / ld65 and writes
# bas_loader.h: the image, its sector count, the first sector of the program's stream and the
# offsets the firmware patches. bas_loader.h is kept in the repository, so the firmware builds
# without cc65; run this after changing bas_loader.s.
import os, re, subprocess, sys, tempfile
here = os.path.dirname(os.path.abspath(__file__))
with tempfile.TemporaryDirectory() as t:
    cfg = os.path.join(t, "bl.cfg")
    open(cfg, "w").write("MEMORY { RAM: start = $0700, size = $1000, file = %O; }\n"
                         "SEGMENTS { CODE: load = RAM, type = rw; }\n")
    o, b, lbl = (os.path.join(t, n) for n in ("bl.o", "bl.bin", "bl.lbl"))
    subprocess.run(["ca65", "-o", o, os.path.join(here, "bas_loader.s")], check=True)
    subprocess.run(["ld65", "-C", cfg, "-o", b, "-Ln", lbl, o], check=True)
    img = open(b, "rb").read()
    sym = {m.group(2): int(m.group(1), 16) for m in re.finditer(r"al ([0-9A-F]+) \.(\w+)", open(lbl).read())}
nsec = sym["NSEC"]
assert nsec * 128 >= len(img) and nsec <= 4
img = img + bytes(nsec * 128 - len(img))
out = ["// Generated by bas_loader.py from bas_loader.s: do not edit.",
       "#define BAS_NSEC %d          // sectors of the boot program (1..BAS_NSEC)" % nsec,
       "#define BAS_DATASEC 5        // the BASIC program's first sector",
       "#define BAS_P_LEN 0x%03X      // u24: the program's length in bytes" % sym["P_LEN"],
       "#define BAS_P_MODE 0x%03X     // 0 a listing (ENTER), 1 a SAVE file (RUN)" % sym["P_MODE"],
       "static const unsigned char bas_loader_img[%d] = {" % len(img)]
for i in range(0, len(img), 16):
    out.append("    " + ", ".join("0x%02X" % x for x in img[i:i + 16]) + ",")
out.append("};")
open(os.path.join(here, "bas_loader.h"), "w").write("\n".join(out) + "\n")
print("bas_loader.h: %d bytes, %d sectors" % (len(img), nsec))
