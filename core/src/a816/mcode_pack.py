"""Compress the 65C816 microcode ROM (mcode.sv, 2048 x 52 bits = 6 block RAMs).

Only 273 distinct microinstructions exist. The fields are split into groups; each group
is stored as a small code and expanded by a LUT ROM after the output register, so the
block RAM shrinks to 2048 x (sum of code widths). Writes mcode_packed.sv, a drop-in
replacement for mcode.sv, and checks every defined entry expands to the original bits.

  mcode_pack.py            3 groups, <= 18 bits -> 2 block RAMs
  mcode_pack.py --index    1 group,  9 bits  -> 1 block RAM, bigger LUT decode
"""
import re, sys, math, random
NAMES = ['stateCtrl','addrBus','addrInc','loadP','loadT','muxCtrl','addrCtrl','loadPC','loadSP',
         'regAXY','loadDKB','busCtrl','ALUCtrl','byteSel','outBus','va']
src = open('mcode.sv').read()
ent = {}
for m in re.finditer(r"M_TAB\[(\d+)\]=\{(.*?)\};", src):
    ent[int(m.group(1))] = tuple(x.split("'b")[1] for x in m.group(2).split(', '))
assert len(ent) == 2048
W = [len(f) for f in ent[0]]
real = {i: e for i, e in ent.items() if 'X' not in ''.join(e)}
RESET = ent[2047]                      # the STATE==0 (opcode fetch) microinstruction
rl = list(set(real.values()))

def uniq(g): return len(set(tuple(e[i] for i in g) for e in rl))
def bits(g): return max(1, math.ceil(math.log2(uniq(g)))) if g else 0

if '--index' in sys.argv:
    groups = [list(range(16))]
else:
    random.seed(7); best = None
    P = lambda a: [[i for i in range(16) if a[i] == g] for g in range(3)]
    cost = lambda a: sum(1 << bits(g) for g in P(a))     # total decode-ROM depth
    for _ in range(60):                # local search: 3 groups, smallest decode ROMs
        a = [random.randrange(3) for _ in range(16)]
        c = cost(a); imp = True
        while imp:
            imp = False
            for i in range(16):
                for g in range(3):
                    if g != a[i]:
                        b = a[:]; b[i] = g; cb = cost(b)
                        if cb < c: a, c, imp = b, cb, True
        if best is None or c < best[0]: best = (c, P(a))
    groups = [g for g in best[1] if g]
cw = [bits(g) for g in groups]
TW = sum(cw)
print('groups:', [([NAMES[i] for i in g], uniq(g), w) for g, w in zip(groups, cw)], 'total bits', TW)

codes = []                             # per group: {field tuple: code}, reset value = code 0
for g in groups:
    d = {tuple(RESET[i] for i in g): 0}
    for e in sorted(rl):
        d.setdefault(tuple(e[i] for i in g), len(d))
    codes.append(d)
def enc(e):
    if 'X' in ''.join(e): return 0
    v = 0
    for g, d, w in zip(groups, codes, cw): v = (v << w) | d[tuple(e[i] for i in g)]
    return v
def dec(v):                            # model of the generated decode, for the self-check
    out = [None] * 16
    for g, d, w in reversed(list(zip(groups, codes, cw))):
        inv = {c: k for k, c in d.items()}[v & ((1 << w) - 1)]; v >>= w
        for i, f in zip(g, inv): out[i] = f
    return tuple(out)
for i, e in real.items(): assert dec(enc(e)) == e, i
assert enc(RESET) == 0
print('self-check OK: %d defined entries, %d distinct' % (len(real), len(rl)))

head = src[:src.index('   logic [51:0] M_TAB')]
m = re.search(r"\n(\s*MicroInst_r\s+MI;.*?)(\n\s*// micro code format:)", src, re.S)
assert m, 'ALUFlags section not found'
o = [head.replace('// TODO: Micro code here should be compressed.', '// GENERATED by mcode_pack.py from mcode.sv - do not edit.\n// TODO (done): Micro code here should be compressed.')]
o.append('   logic [%d:0] M_TAB [0:2047] /* synthesis syn_romstyle = "block_rom" */;\n   logic [%d:0] MQ;\n   initial begin\n' % (TW - 1, TW - 1))
for i in range(2048): o.append("M_TAB[%d]=%d'd%d;\n" % (i, TW, enc(ent[i])))
o.append('   end\n')
o.append(m.group(1) + '\n')
o.append('''
    // packed microcode: registered block-RAM read, reset = the opcode-fetch microinstruction (code 0)
    always @(posedge CLK or negedge RST_N)
    begin
        reg [3:0] STATE2;
        if (~RST_N)
            MQ <= '0;
        else begin
            STATE2 = STATE - 4'd1;
            if (EN == 1'b1)
                MQ <= M_TAB[STATE == 4'b0 ? 11'd2047 : {IR, STATE2[2:0]}];
        end
    end
''')
pos = TW
for gi, (g, d, w) in enumerate(zip(groups, codes, cw)):
    pos -= w
    lhs = '{' + ', '.join('MI.' + NAMES[i] for i in g) + '}'
    gw = sum(W[i] for i in g)
    o.append("    always_comb begin\n        case (MQ[%d:%d])\n" % (pos + w - 1, pos))
    for k, c in sorted(d.items(), key=lambda x: x[1]):
        o.append("        %d'd%d: %s = %d'b%s;\n" % (w, c, lhs, gw, ''.join(k)))
    o.append("        default: %s = 'x;\n        endcase\n    end\n" % lhs)
o.append('''   assign M = {ALUFlags, MI.stateCtrl, MI.addrBus, MI.addrInc, MI.muxCtrl, MI.addrCtrl, MI.loadPC, MI.loadSP,
               MI.regAXY, MI.loadP, MI.loadT, MI.loadDKB, MI.busCtrl, MI.byteSel, MI.outBus, MI.va};

endmodule
''')
out = 'mcode_index.sv' if '--index' in sys.argv else 'mcode_packed.sv'
open(out, 'w').write(''.join(o))
print('wrote', out)
