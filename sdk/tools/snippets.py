#!/usr/bin/env python3
"""snippets.py - assemble and link every ```asm example of the reference.

    snippets.py [--horizon DIR] [--ref DIR] [--out DIR] [-v]

Each Markdown file's examples become one program: every example in a .scope of its own,
inside a harness that provides the names the examples use (buf, blk, ev, path, iob in
BSS; win, fh, n, t0, t1 in ZEROPAGE; stubs for getev, handle, step, draw, mul320). The
program is assembled with ca65 and linked with ld65 against ulib.o and ui.lib, as a real
program would be. A failure prints the example's file and line. The programs are not
run (the templates and examples are: make test).
"""
import glob
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

HEAD = """; generated by snippets.py from {src}
        .include "horizon.inc"
        .include "ui.inc"
        .segment "CODE"
        .a16
        .i16
start:  exit    0
getev:
handle:
step:
draw:
mul320: rts
"""
TAIL = """
        .segment "BSS"
buf:    .res    256
blk:    .res    16
ev:     .res    8
path:   .res    128
iob:    .res    6
        .segment "ZEROPAGE"
win:    .res    2
fh:     .res    2
n:      .res    2
t0:     .res    4
t1:     .res    4
t2:     .res    2
t3:     .res    2
keys:   .res    2
pending: .res   2
"""


def blocks(path):
    out, cur, start = [], None, 0
    for no, ln in enumerate(open(path, encoding='utf-8'), 1):
        if cur is None and ln.strip() == '```asm':
            cur, start = [], no + 1
        elif cur is not None and ln.strip() == '```':
            out.append((start, cur)); cur = None
        elif cur is not None:
            cur.append(ln.rstrip('\n'))
    return out


def main():
    a = sys.argv[1:]
    hz = os.environ.get('HORIZON') or os.path.join(HERE, '..', '..', 'horizon')
    ref = os.path.join(HERE, '..', 'docs', 'reference')
    out = os.path.join(HERE, '..', 'build', 'snippets')
    verbose = False
    i = 0
    while i < len(a):
        if a[i] == '--horizon': hz = a[i + 1]; i += 2
        elif a[i] == '--ref': ref = a[i + 1]; i += 2
        elif a[i] == '--out': out = a[i + 1]; i += 2
        elif a[i] == '-v': verbose = True; i += 1
        elif a[i] in ('-h', '--help'): print(__doc__); return 0
        else: sys.exit(f'snippets: unknown argument {a[i]}')
    os.makedirs(out, exist_ok=True)
    user = os.path.join(hz, 'user')
    libs = [os.path.join(hz, 'build', 'ulib.o'), os.path.join(hz, 'build', 'ui.lib')]
    for l in libs:
        if not os.path.exists(l):
            sys.exit(f'snippets: {l} missing: make -C {hz} build/ulib.o build/ui.lib')
    total, bad = 0, 0
    for md in sorted(glob.glob(os.path.join(ref, '*.md'))):
        bl = blocks(md)
        if not bl:
            continue
        name = os.path.splitext(os.path.basename(md))[0]
        src = [HEAD.format(src=os.path.basename(md))]
        linemap = {}
        for k, (start, lines) in enumerate(bl):
            src.append(f'        .segment "CODE"\n        .scope  ex{k}\nex{k}_start:')
            base = sum(s.count('\n') for s in src) + 1
            for j, l in enumerate(lines):
                linemap[base + j] = (start + j, l)
            src.append('\n'.join(lines))
            src.append('        .a16\n        .i16\n        .endscope')
        src.append(TAIL)
        asm = os.path.join(out, name + '.s')
        open(asm, 'w').write('\n'.join(src) + '\n')
        obj = asm[:-2] + '.o'
        prg = asm[:-2] + '.prg'
        total += len(bl)
        r = subprocess.run(['ca65', '-I', user, '-o', obj, asm], capture_output=True, text=True)
        if r.returncode == 0:
            r = subprocess.run(['ld65', '-C', os.path.join(user, 'prog.cfg'), '-o', prg, obj] + libs,
                               capture_output=True, text=True)
        msgs = (r.stdout + r.stderr).strip()
        if r.returncode != 0 or ('Warning' in msgs and verbose):
            for m in msgs.splitlines():
                mm = re.match(r'.*?\.s:(\d+): (.*)', m)
                if mm and int(mm.group(1)) in linemap:
                    ln, text = linemap[int(mm.group(1))]
                    print(f'{os.path.basename(md)}:{ln}: {mm.group(2)}   [{text.strip()}]')
                else:
                    print(f'{os.path.basename(md)}: {m}')
        if r.returncode != 0:
            bad += 1
        elif verbose:
            print(f'ok  {os.path.basename(md)}: {len(bl)} examples')
    print(f'snippets: {total} examples in {len(glob.glob(os.path.join(ref, "*.md")))} files: '
          + ('FAILED' if bad else 'all assemble and link'))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
