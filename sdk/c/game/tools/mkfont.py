#!/usr/bin/env python3
"""mkfont.py - hgame's built-in font (game/hg_font.c) from Horizon's console font.

    mkfont.py HORIZON/kernel/font8x12.txt -o hg_font.c

The console font is 8 x 12 cells, ASCII 32-126, an original design for Horizon. Its glyphs
use rows 1-10 and columns 1-6 of the cell; hgame keeps rows 1-10 (8 x 10 cells: 40 x 18
characters on a 320 x 180 screen), one byte a row, bit 7 the leftmost pixel.
"""
import re
import sys


def main():
    a = sys.argv[1:]
    if len(a) != 3 or a[1] != "-o":
        sys.exit(__doc__)
    glyphs, code, rows = {}, None, []
    for ln in open(a[0]):
        if ln.startswith(";"):
            continue
        m = re.match(r"char ([0-9a-fA-F]{2})", ln)
        if m:
            if code is not None:
                glyphs[code] = rows
            code, rows = int(m.group(1), 16), []
            continue
        s = ln.rstrip("\n")
        if code is not None and re.fullmatch(r"[.#]{6}", s):
            rows.append(s)
    if code is not None:
        glyphs[code] = rows
    out = ["/* hg_font.c - hgame's built-in font: 8 x 10 cells, ASCII 32-126, one byte a row",
           " * (bit 7 = the leftmost pixel). GENERATED by game/tools/mkfont.py from Horizon's",
           " * console font (horizon/kernel/font8x12.txt, an original design): do not edit. */",
           '#include "hg_int.h"', "",
           "const unsigned char hg__font[95 * 10] = {"]
    for c in range(32, 127):
        r = glyphs.get(c, ["......"] * 10)
        if len(r) != 10:
            sys.exit(f"mkfont: char {c:02x} has {len(r)} rows")
        bs = []
        for row in r:
            v = 0
            for i, ch in enumerate(row):
                if ch == "#":
                    v |= 0x40 >> i
            bs.append(v)
        out.append("    " + ", ".join(f"0x{v:02X}" for v in bs) + ",   /* " +
                   (chr(c) if c not in (0x2A, 0x2F, 0x5C) else f"0x{c:02X}") + " */")
    out.append("};")
    open(a[2], "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
