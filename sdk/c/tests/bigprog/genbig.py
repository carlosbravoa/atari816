#!/usr/bin/env python3
"""genbig.py - a C program with far more code than one bank holds, for cc816's large code
model (hcc --code large), and the output it must print.

    genbig.py OUTDIR [--funcs N] [--files F] [--seed S]

Writes OUTDIR/big0.c .. big<F-1>.c (the functions), OUTDIR/bigmain.c (main, a table of
function pointers, two functions that call each other recursively from the first and the
last file) and OUTDIR/expected.txt (the lines the program prints, computed here the way
the C does it: 16-bit unsigned arithmetic). Each function f<k>(x, d) computes a value from
x and, while d > 0, calls another function (any of them: the files end up in different
banks) directly or through the table, with a switch (a jump table), a 32-bit product (a
runtime helper) or a 64-bit one (long long); main calls every function with d = 2 and
prints a checksum every 250 functions. Default: 1,600 functions in 8 files, about 195 KB
of code.
"""
import os
import random
import sys

M16 = 0xFFFF


def main():
    a = sys.argv[1:]
    if not a:
        sys.exit(__doc__)
    out = a[0]
    n, nf, seed = 1600, 8, 1
    i = 1
    while i < len(a):
        if a[i] == "--funcs":
            n = int(a[i + 1]); i += 2
        elif a[i] == "--files":
            nf = int(a[i + 1]); i += 2
        elif a[i] == "--seed":
            seed = int(a[i + 1]); i += 2
        else:
            sys.exit(__doc__)
    rnd = random.Random(seed)
    os.makedirs(out, exist_ok=True)
    T = 64
    tab = [rnd.randrange(n) for _ in range(T)]
    fns = []
    for k in range(n):
        f = {"A": rnd.randrange(1, 300) | 1, "B": rnd.randrange(65536), "C": rnd.randrange(65536),
             "S": rnd.randrange(1, 5), "J": rnd.randrange(n), "kind": rnd.choice(
                 ["call", "call", "ptr", "switch", "long", "llong"])}
        if f["kind"] == "switch":
            f["cases"] = [rnd.randrange(1, 65536) for _ in range(8)]
        if f["kind"] in ("long", "llong"):
            f["M"] = rnd.randrange(1, 65536)
        fns.append(f)

    def model(k, x, d):
        f = fns[k]
        y = (x * f["A"] + f["B"]) & M16
        if d == 0:
            return y ^ f["C"]
        kind = f["kind"]
        if kind == "call":
            y = (y + model(f["J"], y >> f["S"], d - 1)) & M16
        elif kind == "ptr":
            y = (y + model(tab[y % T], y, d - 1)) & M16
        elif kind == "switch":
            c = f["cases"][y & 7]
            if (y & 7) % 2:
                y ^= c
            else:
                y = (y + c) & M16
            y = (y + model(f["J"], y, d - 1)) & M16
        elif kind == "long":
            y = ((y * f["M"]) >> 8) & M16
            y = (y ^ model(f["J"], y >> 1, d - 1)) & M16
        else:
            y = ((y * y * f["M"]) >> 20) & M16
            y = (y ^ model(f["J"], y, d - 1)) & M16
        return (y ^ (y >> 3) ^ f["C"]) & M16

    def body(k):
        f = fns[k]
        L = [f"unsigned f{k}(unsigned x, unsigned d)", "{",
             f"    unsigned y = x * {f['A']}u + {f['B']}u;",
             f"    if (d == 0)", f"        return y ^ {f['C']}u;"]
        kind = f["kind"]
        if kind == "call":
            L.append(f"    y += f{f['J']}(y >> {f['S']}, d - 1);")
        elif kind == "ptr":
            L.append(f"    y += big_tab[y % {T}u](y, d - 1);")
        elif kind == "switch":
            L.append("    switch (y & 7) {")
            for c, v in enumerate(f["cases"]):
                L.append(f"    case {c}: y {'^=' if c % 2 else '+='} {v}u; break;")
            L.append("    }")
            L.append(f"    y += f{f['J']}(y, d - 1);")
        elif kind == "long":
            L.append(f"    y = (unsigned)(((unsigned long)y * {f['M']}u) >> 8);")
            L.append(f"    y ^= f{f['J']}(y >> 1, d - 1);")
        else:
            L.append(f"    y = (unsigned)(((unsigned long long)y * y * {f['M']}u) >> 20);")
            L.append(f"    y ^= f{f['J']}(y, d - 1);")
        L += ["    return y ^ (y >> 3) ^ " + f"{f['C']}u;", "}"]
        return "\n".join(L)

    decl = "\n".join(f"unsigned f{k}(unsigned, unsigned);" for k in range(n))
    hdr = ("/* generated by tests/large/genbig.py */\n"
           "typedef unsigned (*big_fn)(unsigned, unsigned);\n"
           f"extern big_fn const big_tab[{T}];\n" + decl + "\n"
           "unsigned rec_a(unsigned n);\nunsigned rec_b(unsigned n);\n")
    with open(os.path.join(out, "big.h"), "w") as fh:
        fh.write(hdr)
    per = -(-n // nf)
    for fi in range(nf):
        with open(os.path.join(out, f"big{fi}.c"), "w") as fh:
            fh.write('#include "big.h"\n\n')
            for k in range(fi * per, min(n, (fi + 1) * per)):
                fh.write(body(k) + "\n\n")
            if fi == 0:
                fh.write("unsigned rec_a(unsigned n)\n{\n    return n ? rec_b(n - 1) + 3 : 1;\n}\n")
            if fi == nf - 1:
                fh.write("unsigned rec_b(unsigned n)\n{\n    return n ? (rec_a(n - 1) * 2) % 1000"
                         " : 2;\n}\n")
    with open(os.path.join(out, "bigmain.c"), "w") as fh:
        fh.write('#include <stdio.h>\n#include "big.h"\n\n')
        fh.write(f"big_fn const big_tab[{T}] = {{\n" +
                 ",\n".join(f"    f{t}" for t in tab) + "\n};\n\n")
        fh.write("int main(void)\n{\n    unsigned k, acc = 0;\n"
                 f"    printf(\"big: {n} functions\\n\");\n"
                 f"    for (k = 0; k < {n}u; k++) {{\n"
                 "        acc = acc * 31u + big_tab[k % 64u](k, 0) + 7u;\n"
                 "        acc ^= (k & 1) ? f0(k, 1) : 0;\n"
                 "    }\n"
                 "    printf(\"table %u\\n\", acc);\n    acc = 0;\n"
                 f"    for (k = 0; k < {n}u; k++) {{\n")
        # every function, called directly: a switch on k would be huge; a table of
        # pointers to all of them is in the main bank (2 bytes each)
        fh.write("        acc = acc * 31u + big_all[k](k, 2);\n"
                 "        if (k % 250u == 249u)\n"
                 "            printf(\"sum %u: %u\\n\", k + 1, acc);\n"
                 "    }\n"
                 "    printf(\"rec %u %u\\n\", rec_a(300), rec_b(301));\n"
                 "    printf(\"big done\\n\");\n    return 0;\n}\n")
    # big_all: every function's address (each needs a thunk if it is in another bank)
    with open(os.path.join(out, "bigmain.c")) as fh:
        txt = fh.read()
    txt = txt.replace("int main(void)", f"static big_fn const big_all[{n}] = {{\n" +
                      ",\n".join(f"    f{k}" for k in range(n)) + "\n};\n\nint main(void)")
    with open(os.path.join(out, "bigmain.c"), "w") as fh:
        fh.write(txt)
    # the expected output
    exp = [f"big: {n} functions"]
    acc = 0
    for k in range(n):
        acc = (acc * 31 + model(tab[k % 64], k, 0) + 7) & M16
        acc ^= model(0, k, 1) if k & 1 else 0
    exp.append(f"table {acc}")
    acc = 0
    for k in range(n):
        acc = (acc * 31 + model(k, k, 2)) & M16
        if k % 250 == 249:
            exp.append(f"sum {k + 1}: {acc}")

    def ra(m):
        return rb(m - 1) + 3 if m else 1

    def rb(m):
        return (ra(m - 1) * 2) % 1000 if m else 2
    sys.setrecursionlimit(5000)
    exp.append(f"rec {ra(300) & M16} {rb(301) & M16}")
    exp.append("big done")
    with open(os.path.join(out, "expected.txt"), "w") as fh:
        fh.write("\n".join(exp) + "\n")
    print(f"genbig: {n} functions in {nf} files, {out}")


if __name__ == "__main__":
    main()
