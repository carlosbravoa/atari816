"""cc816 driver: C -> ca65 assembly -> o65 objects -> a Horizon program (ld65, prog.cfg).

    cc816.py [options] file.c ...         compile and link a program (default a.prg)
      -S        stop after the assembly (.s)
      -c        stop after the object (.o)
      -o FILE   output
      -I DIR    include directory      -D NAME[=VAL]  define a macro
      -O0 / -O1 / -O2 (default)        optimisation level
      --ir      print the IR after optimisation (stderr)
      -l LIB    an extra ca65 library/object to link (repeatable)
"""
import os
import shutil
import subprocess
import sys
import io

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, 'vendor'))

from pycparser import c_parser                     # noqa: E402
from pcpp.preprocessor import Preprocessor, OutputDirective, Action   # noqa: E402

from .ctypes816 import CError                     # noqa: E402
from .front import Front                           # noqa: E402
from . import opt as optmod                        # noqa: E402
from .regalloc import allocate                     # noqa: E402
from .gen import Gen, DP_NAMES                     # noqa: E402
from .peep import peephole, text                   # noqa: E402

INCLUDE = os.path.join(ROOT, 'include')
RT = os.path.join(ROOT, 'rt')
HORIZON = os.path.abspath(os.path.join(ROOT, '..', '..', '..', 'horizon'))
BUILD = os.path.join(ROOT, 'build')

PREDEF = ['__CC816__ 1', '__65816__ 1', '__HORIZON__ 1', '__ATARI816__ 1', '__far _Atomic',
          '__STDC__ 1', '__STDC_VERSION__ 199901L', '__CHAR_UNSIGNED__ 1',
          '__attribute__(x) ', '__near ', '__builtin_expect(x, y) (x)', '__extension__ ']


class PP(Preprocessor):
    def on_error(self, file, line, msg):
        raise CError(f'{file}:{line}: preprocessor: {msg}')

    def on_include_not_found(self, is_malformed, is_system_include, curdir, includepath):
        raise CError(f'include file not found: {includepath}')

    def on_unknown_macro_in_defined_expr(self, tok):
        return False

    def on_directive_unknown(self, directive, toks, ifpassthru, precedingtoks):
        if directive.value in ('warning', 'ident', 'sccs'):
            return None
        if directive.value == 'error':
            raise CError('#error ' + ''.join(t.value for t in toks))
        return None


def preprocess(path, incs, defs):
    p = PP()
    p.auto_pragma_once_enabled = False      # its guess is wrong for multi-pass headers
    p.line_directive = '#line'
    p.compress = 1
    for d in PREDEF + defs:
        p.define(d.replace('=', ' ', 1) if '=' in d and ' ' not in d else d)
    for i in incs + [INCLUDE]:
        p.add_path(i)
    with open(path, encoding='latin-1') as fh:
        src = fh.read()
    p.parse(src, source=path)
    out = io.StringIO()
    p.write(out)
    return out.getvalue()


def compile_c(path, incs=(), defs=(), level=2, dump_ir=False):
    """C file -> assembly text (raises CError)"""
    src = preprocess(path, list(incs), list(defs))
    src = _strip_gnu(src)
    try:
        ast = c_parser.CParser().parse(src, path)
    except Exception as e:      # pycparser ParseError
        raise CError(f'parse error: {e}')
    fr = Front(path)
    unit = fr.translate(ast)
    lines_all = []
    helpers = set()
    for f in unit.funcs:
        optmod.optimise(f, level)
        if dump_ir:
            print(f.dump(), file=sys.stderr)
        allocate(f)
        g = Gen(f, unit, {'level': level})
        lines = g.gen()
        lines = peephole(lines, level >= 1)
        helpers |= g.helpers
        lines_all.append((f, lines))
    return emit(unit, lines_all, helpers), unit.warnings


def _strip_gnu(src):
    # tolerate a few GNU spellings pycparser does not know
    for a, b in (('__inline__', 'inline'), ('__inline', 'inline'), ('__restrict', 'restrict'),
                 ('__const', 'const'), ('__signed__', 'signed'), ('__volatile__', 'volatile')):
        src = src.replace(a, b)
    return src


def emit(unit, funcs, helpers):
    out = ['; generated by cc816', '\t.p816', '\t.smart +', '\t.a16', '\t.i16',
           '\t.importzp ' + ', '.join(DP_NAMES)]
    body = []
    exports = set()
    body.append('\t.segment "CODE"')
    for f, lines in funcs:
        if not f.static:
            exports.add(f.name)
        body.append('')
        body.append(text(lines))
    segs = {'RODATA': [], 'DATA': [], 'BSS': []}
    for d in unit.data:
        lines = segs[d.section]
        lines.append(f'{d.name}:')
        if d.export:
            exports.add(d.name)
        if d.section == 'BSS':
            lines.append(f'\t.res {d.size}')
            continue
        for it in d.items:
            if it[0] == 'b':
                b = it[1]
                for k in range(0, len(b), 16):
                    lines.append('\t.byte ' + ','.join(f'${x:02X}' for x in b[k:k + 16]))
            elif it[0] == 'w':
                lines.append(f'\t.addr {_so(it[1], it[2])}')
            elif it[0] == 'f':
                lines.append(f'\t.faraddr {_so(it[1], it[2])}')
                lines.append('\t.byte 0')
    for s, l in segs.items():
        if l:
            body.append(f'\t.segment "{s}"')
            body.extend(l)
    text_all = '\n'.join(body)
    # imports: every extern or helper the text mentions
    import re
    words = set(re.findall(r'[A-Za-z_][A-Za-z0-9_]*', text_all))
    defined = {f.name for f, _ in funcs} | {d.name for d in unit.data}
    imports = sorted((set(unit.externs) | helpers | {'__fpt', '__abs0'}) & words - defined)
    if imports:
        out.append('\t.import ' + ', '.join(imports))
    if exports:
        out.append('\t.export ' + ', '.join(sorted(exports)))
    return '\n'.join(out) + '\n' + text_all + '\n'


def _so(name, off):
    return name + (f'+{off}' if off > 0 else (f'-{-off}' if off < 0 else ''))


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        raise CError(f'{" ".join(cmd)}\n{r.stdout}{r.stderr}')
    return r


def assemble(asm_path, obj_path):
    run(['ca65', '--cpu', '65816', '-I', os.path.join(HORIZON, 'user'), '-I', RT, '-o', obj_path, asm_path])


def runtime_lib():
    """build (if needed) the runtime: crt0.o, hzend.o and libcc816.lib (rt/*.s + lib/*.c)"""
    os.makedirs(BUILD, exist_ok=True)
    lib = os.path.join(BUILD, 'libcc816.lib')
    objs = []
    srcs = []
    for d in (RT, os.path.join(ROOT, 'lib')):
        for n in sorted(os.listdir(d)):
            if n.endswith('.s') or n.endswith('.c'):
                srcs.append(os.path.join(d, n))
    newest_src = max(os.path.getmtime(s) for s in srcs + _compiler_files())
    if os.path.exists(lib) and os.path.getmtime(lib) >= newest_src:
        return os.path.join(BUILD, 'crt0.o'), lib, os.path.join(BUILD, 'hzend.o')
    for s in srcs:
        base = os.path.splitext(os.path.basename(s))[0]
        o = os.path.join(BUILD, base + '.o')
        if s.endswith('.c'):
            asm, w = compile_c(s)
            sp = os.path.join(BUILD, base + '.s')
            with open(sp, 'w') as fh:
                fh.write(asm)
            assemble(sp, o)
        else:
            assemble(s, o)
        if base not in ('crt0', 'hzend'):
            objs.append(o)
    if os.path.exists(lib):
        os.remove(lib)
    run(['ar65', 'a', lib] + objs)
    return os.path.join(BUILD, 'crt0.o'), lib, os.path.join(BUILD, 'hzend.o')


def _compiler_files():
    return [os.path.join(HERE, n) for n in os.listdir(HERE) if n.endswith('.py')]


def link(objs, out, extra=(), mapfile=None):
    crt0, lib, hzend = runtime_lib()
    cmd = ['ld65', '-C', os.path.join(HORIZON, 'user', 'prog.cfg'), '-o', out]
    if mapfile:
        cmd += ['-m', mapfile]
    cmd += [crt0] + list(objs) + list(extra) + [lib, hzend]
    run(cmd)


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    mode = 'link'
    out = None
    incs, defs, files, libs = [], [], [], []
    level = 2
    dump = False
    mapf = None
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == '-S':
            mode = 'asm'
        elif a == '-c':
            mode = 'obj'
        elif a == '-o':
            i += 1
            out = argv[i]
        elif a.startswith('-I'):
            incs.append(a[2:] or argv[i + 1])
            i += 0 if a[2:] else 1
        elif a.startswith('-D'):
            defs.append(a[2:] or argv[i + 1])
            i += 0 if a[2:] else 1
        elif a.startswith('-O'):
            level = int(a[2:] or 2)
        elif a == '--ir':
            dump = True
        elif a == '-m':
            i += 1
            mapf = argv[i]
        elif a == '-l':
            i += 1
            libs.append(argv[i])
        elif a in ('-h', '--help'):
            print(__doc__)
            return 0
        else:
            files.append(a)
        i += 1
    if not files:
        print(__doc__)
        return 2
    objs = []
    try:
        for f in files:
            if f.endswith('.o') or f.endswith('.lib'):
                objs.append(f)
                continue
            # intermediates go next to the output (or in the current directory), never
            # next to the source
            odir = os.path.dirname(os.path.abspath(out)) if out else os.getcwd()
            base = os.path.join(odir, os.path.splitext(os.path.basename(f))[0])
            if f.endswith('.s'):
                asm_path = f
            else:
                asm, warns = compile_c(f, incs, defs, level, dump)
                for w in warns:
                    print(w, file=sys.stderr)
                asm_path = out if (mode == 'asm' and out) else base + '.s'
                with open(asm_path, 'w') as fh:
                    fh.write(asm)
                if mode == 'asm':
                    continue
            obj = out if (mode == 'obj' and out) else base + '.o'
            assemble(asm_path, obj)
            objs.append(obj)
        if mode == 'link':
            link(objs, out or 'a.prg', libs, mapf)
    except CError as e:
        if os.environ.get('CC816_TRACE'):
            raise
        print(f'cc816: {e}', file=sys.stderr)
        return 1
    return 0
