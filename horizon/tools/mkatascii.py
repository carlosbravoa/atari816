#!/usr/bin/env python3
"""mkatascii.py FONT8x12.txt ATASCII.txt OUT.inc - the BBS terminal's 8x8 ATASCII font
(128 glyphs, 8 bytes each, bit 7 = the leftmost pixel; bit 7 of a character code = inverse
video, drawn by the program).

Original: the graphics characters ($00-$1F, $60, $7B-$7F) are the art of ATASCII.txt; the
others ($20-$5F, $61-$7A) come from Horizon's own console font (FONT8x12.txt, tools/mkfont.py's
input): its rows 2-8 (capitals, the x-height) become rows 0-6 and its two descender rows 9-10
are merged into row 7. No Atari ROM data is used."""
import sys

def load(path, cols):
    glyphs, cur = {}, None
    for ln in open(path):
        ln = ln.rstrip('\n')
        if ln.startswith(';') or not ln.strip():
            continue
        if ln.startswith('char '):
            cur = int(ln.split()[1], 16); glyphs[cur] = []
            continue
        glyphs[cur].append(ln[:cols])
    return glyphs

big = load(sys.argv[1], 6)          # rows 1-10 of the 8x12 cell, columns 1-6
art = load(sys.argv[2], 8)
font = []
for c in range(128):
    if c in art:
        rows = art[c]
        assert len(rows) == 8 and all(len(r) == 8 for r in rows), (hex(c), rows)
        b = [sum(1 << (7 - i) for i, p in enumerate(r) if p == '#') for r in rows]
    else:
        assert 0x20 <= c <= 0x7A, hex(c)
        rows = big[c] + [''] * (10 - len(big[c]))
        r12 = [sum(1 << (6 - i) for i, p in enumerate(r) if p == '#') for r in rows]  # cell rows 1-10
        b = r12[1:8] + [r12[8] | r12[9]]
    font.append(b)
out = ['; generated by tools/mkatascii.py from font8x12.txt and atascii.txt - do not edit',
       '; atascii_font: 128 glyphs of 8 bytes (ATASCII $00-$7F), bit 7 = the leftmost pixel',
       'atascii_font:']
for c, b in enumerate(font):
    out.append('        .byte   ' + ', '.join(f'${x:02X}' for x in b) + f'   ; {c:02X}')
open(sys.argv[3], 'w').write('\n'.join(out) + '\n')
