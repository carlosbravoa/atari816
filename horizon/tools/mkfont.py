#!/usr/bin/env python3
"""mkfont.py FONT.txt OUT.inc [HEIGHT] - convert the console font text art into ca65 .byte
data: HEIGHT bytes per glyph (default 12; cell row 0 is blank, the art gives rows 1..,
padding with blank rows), bit 7 = leftmost pixel (art column 0 = cell column 1), ASCII
32-126."""
import sys
H = int(sys.argv[3]) if len(sys.argv) > 3 else 12
glyphs, cur = {}, None
for ln in open(sys.argv[1]):
    ln = ln.rstrip('\n')
    if ln.startswith(';') or not ln.strip():
        continue
    if ln.startswith('char '):
        cur = int(ln.split()[1], 16); glyphs[cur] = []
        continue
    glyphs[cur].append(ln)
out = [f'; generated by tools/mkfont.py from {sys.argv[1].split("/")[-1]} - do not edit ({H} bytes per glyph)']
for c in range(32, 127):
    rows = glyphs[c]
    assert len(rows) <= H - 1 and all(len(r) <= 7 for r in rows), (c, rows)
    b = [0] + [sum(1 << (6 - i) for i, p in enumerate(r) if p == '#') for r in rows]
    b += [0] * (H - len(b))
    out.append('        .byte   ' + ', '.join(f'${x:02X}' for x in b) + f'   ; {c:02X} {chr(c)!r}')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
