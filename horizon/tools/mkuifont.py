#!/usr/bin/env python3
"""mkuifont.py FONT8x12.txt OUT.inc - the proportional UI font of the window system, made
from the console font's own (original) glyph art: each glyph is cut to its ink columns,
rows 2-10 of the 8x12 cell (capitals 7 rows, x-height 6, descenders 2), so narrow letters
(i, l, t, '.', '1') take less room. Output, for ASCII 32-126:
  uif_w:   one byte per glyph: its advance (ink width + 1 pixel of spacing)
  uif_bm:  9 bytes per glyph: rows 2-10, bit 7 = the leftmost ink column."""
import sys
glyphs, cur = {}, None
for ln in open(sys.argv[1]):
    ln = ln.rstrip('\n')
    if ln.startswith(';') or not ln.strip():
        continue
    if ln.startswith('char '):
        cur = int(ln.split()[1], 16); glyphs[cur] = []
        continue
    glyphs[cur].append(ln)
W, BM = [], []
for c in range(32, 127):
    rows = (glyphs[c] + ['......'] * 10)[:10]       # art rows = cell rows 1..10
    rows = rows[1:10]                                 # cell rows 2..10
    cols = [i for i in range(6) if any(r[i] == '#' for r in rows)]
    if c == 32:
        W.append(3); BM.append([0] * 9); continue
    lo, hi = min(cols), max(cols)
    W.append(hi - lo + 2)
    BM.append([sum(1 << (7 - (i - lo)) for i in range(lo, hi + 1) if r[i] == '#') for r in rows])
out = ['; generated by tools/mkuifont.py from kernel/font8x12.txt - do not edit',
       'UIF_H = 9                               ; glyph rows (line height 11 with spacing)',
       'uif_w:']
for i in range(0, 95, 16):
    out.append('        .byte   ' + ', '.join(str(w) for w in W[i:i + 16]))
out.append('uif_bm:')
for c in range(95):
    out.append('        .byte   ' + ', '.join(f'${b:02X}' for b in BM[c]) + f'   ; {chr(c + 32)!r}')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
