#!/usr/bin/env python3
"""mkpointer.py POINTER.txt OUT.inc - NVC pointer image: 32 rows x 8 bytes, 2 bpp,
leftmost pixel in bits 7-6. '.' = 0 (transparent), 'o' = 1, '#' = 2, '+' = 3."""
import sys
rows = [l.rstrip('\n') for l in open(sys.argv[1]) if not l.startswith(';') and l.strip()]
assert len(rows) <= 32
rows += [''] * (32 - len(rows))
val = {'.': 0, 'o': 1, '#': 2, '+': 3}
out = ['; generated by tools/mkpointer.py from kernel/pointer.txt - do not edit']
for r in rows:
    r = r.ljust(32, '.')
    b = []
    for i in range(8):
        x = 0
        for p in r[i * 4:i * 4 + 4]:
            x = x << 2 | val[p]
        b.append(x)
    out.append('        .byte   ' + ', '.join(f'${x:02X}' for x in b))
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
