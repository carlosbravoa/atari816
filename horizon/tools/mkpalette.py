#!/usr/bin/env python3
"""mkpalette.py OUT.inc - the window system's fixed palette (256 x R, G, B), shared by all
programs:
    0-15     UI colours (see the names below; horizon.inc has the same numbers)
    16-231   a 6 x 6 x 6 colour cube: 16 + 36 r + 6 g + b, each 0-5 (0, 51, ... 255)
    232-255  a grey ramp, 8 to 238 in steps of 10"""
import sys
ui = [
    ('BLACK',     (0, 0, 0)),
    ('WHITE',     (255, 255, 255)),
    ('DESK',      (36, 92, 112)),     # desktop background
    ('DESK2',     (46, 104, 124)),    # its dither partner
    ('TITLE',     (28, 60, 132)),     # active title bar
    ('TITLE_OFF', (132, 138, 148)),   # inactive title bar
    ('BODY',      (228, 226, 216)),   # window body
    ('DARK',      (76, 80, 90)),
    ('MID',       (160, 164, 172)),
    ('LIGHT',     (204, 206, 210)),
    ('SELECT',    (52, 100, 204)),    # selection highlight
    ('RED',       (200, 52, 44)),
    ('YELLOW',    (240, 200, 64)),
    ('GREEN',     (60, 156, 80)),
    ('ORANGE',    (232, 128, 40)),
    ('SHADOW',    (36, 40, 48)),
]
pal = [c for _, c in ui]
for r in range(6):
    for g in range(6):
        for b in range(6):
            pal.append((r * 51, g * 51, b * 51))
for i in range(24):
    v = 8 + 10 * i
    pal.append((v, v, v))
assert len(pal) == 256
out = ['; generated by tools/mkpalette.py - do not edit']
for i, (n, _) in enumerate(ui):
    out.append(f'C_{n:10s}= {i}')
out.append('ws_palette:')
for i in range(0, 256, 4):
    out.append('        .byte   ' + ', '.join(f'${c:02X}' for p in pal[i:i + 4] for c in p))
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
