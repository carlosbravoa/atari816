#!/usr/bin/env python3
"""mkicons.py IN.txt OUT.bin OUT.inc [--png PREVIEW.png] - the desktop icons.

IN.txt (see the header of sdfiles/icons.txt): "color C N" lines map a character to a palette
index (global before the first icon, per icon after its "icon NAME" line), and each
"icon NAME" is followed by exactly 32 rows of exactly 32 mapped characters.

OUT.bin  every icon in file order, 1024 bytes each (32 rows of 32 bytes, 255 = transparent)
OUT.inc  ICO_<NAME> = n (its index in the file) and ICO_COUNT
--png    a preview: the icons on the desktop dither, 4x, in a grid with their names"""
import ast, os, re, sys

N = 32


def die(msg):
    sys.exit(f'mkicons: {msg}')


def parse(path):
    glob, icons, cur = {}, [], None
    for no, raw in enumerate(open(path), 1):
        line = re.sub(r'(^|\s)#.*$', '', raw).strip()
        if not line:
            continue
        where = f'{path}:{no}'
        w = line.split()
        if w[0] == 'color':
            if len(w) != 3 or len(w[1]) != 1 or w[1] == '#':
                die(f'{where}: "color C N" expected')
            try:
                v = int(w[2], 0)
            except ValueError:
                die(f'{where}: bad palette index {w[2]!r}')
            if not 0 <= v <= 255:
                die(f'{where}: palette index {v} out of range')
            if cur is None:
                glob[w[1]] = v
            elif cur['rows']:
                die(f'{where}: "color" after the rows of {cur["name"]}')
            else:
                cur['legend'][w[1]] = v
        elif w[0] == 'icon':
            if len(w) != 2 or not re.fullmatch(r'[A-Z][A-Z0-9_]*', w[1]):
                die(f'{where}: "icon NAME" expected (NAME in A-Z, 0-9, _)')
            if any(i['name'] == w[1] for i in icons):
                die(f'{where}: icon {w[1]} defined twice')
            cur = {'name': w[1], 'legend': dict(glob), 'rows': [], 'line': no}
            icons.append(cur)
        else:
            if cur is None:
                die(f'{where}: row before the first "icon"')
            if len(cur['rows']) == N:
                die(f'{where}: icon {cur["name"]} has more than {N} rows')
            if len(line) != N:
                die(f'{where}: icon {cur["name"]} row is {len(line)} characters, not {N}')
            bad = sorted(set(c for c in line if c not in cur['legend']))
            if bad:
                die(f'{where}: icon {cur["name"]}: unmapped character(s) {"".join(bad)!r}')
            cur['rows'].append([cur['legend'][c] for c in line])
    if not icons:
        die(f'{path}: no icons')
    for i in icons:
        if len(i['rows']) != N:
            die(f'{path}:{i["line"]}: icon {i["name"]} has {len(i["rows"])} rows, not {N}')
    return icons


def palette():
    """the same 256 colours as tools/mkpalette.py (its UI list is read from that file)"""
    src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'mkpalette.py')).read()
    m = re.search(r'^ui = (\[.*?^\])', src, re.S | re.M)
    ui = ast.literal_eval(re.sub(r'#.*', '', m.group(1)))
    pal = [c for _, c in ui]
    pal += [(r * 51, g * 51, b * 51) for r in range(6) for g in range(6) for b in range(6)]
    pal += [(8 + 10 * i,) * 3 for i in range(24)]
    assert len(pal) == 256
    return pal


def preview(icons, path, scale=4, cols=7):
    from PIL import Image, ImageDraw, ImageFont
    pal = palette()
    cw, ch = N * scale + 24, N * scale + 30
    rows = (len(icons) + cols - 1) // cols
    W, H = cols * cw, rows * ch
    img = Image.new('RGB', (W, H))
    px = img.load()
    for y in range(H):                      # the desktop dither, at the icons' scale
        for x in range(W):
            px[x, y] = pal[2 if (x // scale + y // scale) % 2 == 0 else 3]
    d = ImageDraw.Draw(img)
    font = ImageFont.load_default()
    for n, ic in enumerate(icons):
        ox, oy = (n % cols) * cw + 12, (n // cols) * ch + 6
        for y, row in enumerate(ic['rows']):
            for x, v in enumerate(row):
                if v != 255:
                    d.rectangle([ox + x * scale, oy + y * scale, ox + x * scale + scale - 1,
                                 oy + y * scale + scale - 1], fill=pal[v])
        tw = d.textlength(ic['name'], font=font)
        d.text((ox + (N * scale - tw) / 2, oy + N * scale + 6), ic['name'], fill=(255, 255, 255), font=font)
    img.save(path)


def main():
    a = sys.argv[1:]
    png = None
    if '--png' in a:
        k = a.index('--png')
        if k + 1 >= len(a):
            die('--png needs a file name')
        png = a[k + 1]
        del a[k:k + 2]
    if len(a) != 3:
        sys.exit(__doc__)
    src, binf, inc = a
    icons = parse(src)
    with open(binf, 'wb') as f:
        for i in icons:
            f.write(bytes(v for row in i['rows'] for v in row))
    out = [f'; generated by tools/mkicons.py from {os.path.basename(src)} - do not edit',
           f'; {len(icons)} icons, 32 x 32, 8 bpp, 1024 bytes each, 255 = transparent']
    out += [f'ICO_{i["name"]} = {n}' for n, i in enumerate(icons)]
    out.append(f'ICO_COUNT = {len(icons)}')
    open(inc, 'w').write('\n'.join(out) + '\n')
    if png:
        preview(icons, png)


main()
